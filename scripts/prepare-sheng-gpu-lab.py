#!/usr/bin/env python3
"""Add signed GPU acceptance tools and current lab scripts to a timed RAM boot."""
import argparse
import json
import os
from pathlib import Path
import re
import shutil
import struct
import subprocess
import sys
import tempfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]


def run(*command, **kwargs):
    subprocess.run([str(value) for value in command], check=True, **kwargs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input', type=Path)
    parser.add_argument('output', type=Path)
    parser.add_argument('--tools', type=Path, action='append', required=True)
    parser.add_argument('--plugin', type=Path, required=True, help='current signed macos27 GPU build directory')
    parser.add_argument('--icd', type=Path, help='ICD JSON generated by the matching Turnip build')
    parser.add_argument('--payload-mib', type=int, default=256, help='decoded FAT volume size in MiB')
    parser.add_argument('--video-fixture', type=Path, help='HEVC MP4 for the timed VideoToolbox decode probe')
    parser.add_argument('--video-fixture-10bit', type=Path, help='additional 10-bit HEVC MP4 for pixel and frame checks')
    parser.add_argument('--icon-path', help='one guest application or preference pane for icon isolation')
    parser.add_argument('--icon-dump-cb', help='bounded FIRST:COUNT command-buffer dump for the isolated icon service')
    parser.add_argument('--preserve-data', action='store_true')
    parser.add_argument('--bluetooth-runtime', type=Path, help='signed runtime report from build-bluetooth-userspace.py')
    parser.add_argument('--refresh-payload', action='store_true', help='build the current board menu, ADT and firmware transport')
    parser.add_argument('--uefi', type=Path, help='built firmware checkout for --refresh-payload')
    parser.add_argument('--unique-chip-id', help='device platform seed for --refresh-payload')
    parser.add_argument('--autoreset', type=int, default=7200)
    args = parser.parse_args()
    if args.output.exists() or args.input.resolve() == args.output.resolve():
        parser.error('choose a new output file')
    if args.refresh_payload and not args.uefi:
        parser.error('--refresh-payload requires --uefi')
    if args.icon_dump_cb and (not args.icon_path or not re.fullmatch(r'[1-9][0-9]*:[1-9][0-9]*', args.icon_dump_cb)
                             or int(args.icon_dump_cb.split(':')[1]) > 32):
        parser.error('--icon-dump-cb requires --icon-path and FIRST:COUNT with COUNT at most 32')
    core = (ROOT / tomllib.loads((ROOT / 'board.toml').read_text())['package']['unixnu']).resolve()
    sys.path.insert(0, str(core / 'scripts'))
    from unixnu import ramdisk as codec
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='sheng-gpu-lab-', dir=args.output.parent) as directory:
        work = Path(directory)
        with args.input.open('rb') as source:
            header = source.read(4096)
            if header[:8] != b'ANDROID!':
                parser.error('require a sheng Android boot image')
            kernel, _, ramdisk, _, _, _, _, page, version, _ = struct.unpack_from('<10I', header, 8)
            if version != 0 or page < 2048 or page & (page - 1):
                parser.error('require the sheng header-v0 layout')
            source.seek(page + (kernel + page - 1) // page * page)
            payload = work / 'payload.img'
            with payload.open('wb') as target:
                left = ramdisk
                while left:
                    data = source.read(min(left, 8 * 1024 * 1024))
                    if not data:
                        parser.error('truncated payload')
                    target.write(data)
                    left -= len(data)
        if codec.packed(payload):
            decoded = work / 'decoded.img'
            codec.decode(payload, decoded, core)
            payload = decoded
        original_addon, original_trust = work / 'original-addon.bin', work / 'original-trust.bundle'
        prefix = 'EFI/UniXNU/Payloads/kernel.macho.'
        run('mcopy', '-i', payload, '::/' + prefix + 'gpuaddon', original_addon)
        run('mcopy', '-i', payload, '::/' + prefix + 'trustcache', original_trust)
        files = work / 'files'
        for tools in args.tools:
            shutil.copytree(tools, files, dirs_exist_ok=True)
        sdk = subprocess.check_output(['xcrun', '--sdk', 'macosx', '--show-sdk-path'], text=True).strip()
        run('xcrun', 'clang', '-target', 'arm64e-apple-macos27.0', '-isysroot', sdk,
            '-O2', '-Wall', '-Wextra', '-Werror', '-fobjc-arc', '-framework', 'AppKit',
            '-framework', 'QuartzCore', ROOT / 'scripts/macos-lab/scene.m',
            '-Wl,-segalign,0x4000', '-o', files / 'bin/gpu-scene')
        run('codesign', '--force', '--sign', '-', '--timestamp=none', '--pagesize', '4096', files / 'bin/gpu-scene')
        run('xcrun', 'clang', '-target', 'arm64e-apple-macos27.0', '-isysroot', sdk,
            '-O2', '-Wall', '-Wextra', '-Werror', ROOT / 'scripts/macos-lab/clock-probe.c',
            '-Wl,-segalign,0x4000', '-o', files / 'bin/clock-probe')
        run('codesign', '--force', '--sign', '-', '--timestamp=none', '--pagesize', '4096', files / 'bin/clock-probe')
        run('xcrun', 'clang', '-target', 'arm64e-apple-macos27.0', '-isysroot', sdk,
            '-O2', '-Wall', '-Wextra', '-Werror', '-fobjc-arc', '-framework', 'AppKit',
            '-framework', 'CoreImage', '-framework', 'Metal', ROOT / 'scripts/macos-lab/icon-probe.m',
            '-Wl,-segalign,0x4000', '-o', files / 'bin/icon-probe')
        run('codesign', '--force', '--sign', '-', '--timestamp=none', '--pagesize', '4096', files / 'bin/icon-probe')
        run('xcrun', 'clang', '-target', 'arm64e-apple-macos27.0', '-isysroot', sdk,
            '-O2', '-Wall', '-Wextra', '-Werror', '-fobjc-arc', '-framework', 'Foundation',
            '-framework', 'Metal', '-framework', 'IOSurface', ROOT / 'scripts/macos-lab/gpu-correctness-probe.m',
            '-Wl,-segalign,0x4000', '-o', files / 'bin/gpu-correctness-probe')
        run('codesign', '--force', '--sign', '-', '--timestamp=none', '--pagesize', '4096', files / 'bin/gpu-correctness-probe')
        (files / 'share').mkdir(exist_ok=True)
        (files / 'share/icon-probe-path').write_text(args.icon_path+'\n' if args.icon_path else '')
        for name in ('video-probe.mp4', 'video-probe-10bit.mp4'):
            (files / 'share' / name).write_bytes(b'')
        if args.video_fixture:
            run('xcrun', 'clang', '-target', 'arm64e-apple-macos27.0', '-isysroot', sdk,
                '-O2', '-Wall', '-Wextra', '-Werror', '-Wno-deprecated-declarations', '-fobjc-arc',
                '-framework', 'AVFoundation', '-framework', 'VideoToolbox', '-framework', 'CoreMedia',
                '-framework', 'CoreVideo', ROOT / 'scripts/macos-lab/video-probe.m',
                '-Wl,-segalign,0x4000', '-o', files / 'bin/video-probe')
            run('codesign', '--force', '--sign', '-', '--timestamp=none', '--pagesize', '4096', files / 'bin/video-probe')
            (files / 'share').mkdir(exist_ok=True)
            shutil.copyfile(args.video_fixture, files / 'share/video-probe.mp4')
            if args.video_fixture_10bit:
                shutil.copyfile(args.video_fixture_10bit, files / 'share/video-probe-10bit.mp4')
        for name in ('bin/gpu-acceptance', 'lib/libvulkan.1.dylib', 'lib/libVkLayer_khronos_validation.dylib'):
            if not (files / name).is_file():
                parser.error('missing diagnostic input: ' + name)
        icd = files / 'etc/vulkan/icd.d/turnip.json'
        icd.parent.mkdir(parents=True, exist_ok=True)
        generated_icd = args.icd or core / 'build/mesa-tu-macos27/src/freedreno/vulkan/freedreno_icd.arm64.json'
        driver = json.loads(generated_icd.read_text())
        driver['ICD']['library_path'] = '/Library/GPUBundles/NativeAdrenoMetal.bundle/Contents/MacOS/libvulkan_freedreno.dylib'
        icd.write_text(json.dumps(driver, indent=2) + '\n')
        hashes = []
        bluetooth_dirs = []
        if args.bluetooth_runtime:
            report = json.loads((args.bluetooth_runtime / 'report.json').read_text())
            for addon_prefix, directory in report['directories'].items():
                bluetooth_dirs += [addon_prefix, args.bluetooth_runtime / directory]
            hashes.extend(item['cdhash'] for item in report['files'].values())
        code = args.plugin / 'NativeAdrenoMetal.bundle/Contents/MacOS'
        for path in sorted(files.rglob('*')) + sorted(code.iterdir()):
            if not path.is_file():
                continue
            with path.open('rb') as source:
                magic = source.read(4)
            if magic not in (b'\xcf\xfa\xed\xfe', b'\xca\xfe\xba\xbe'):
                continue
            run('codesign', '--verify', '--strict', path)
            if magic == b'\xcf\xfa\xed\xfe':
                with path.open('rb') as image:
                    _, cpu, subtype = struct.unpack('<III', image.read(12))
                if cpu != 0x100000c or subtype & 0xffffff != 2:
                    raise SystemExit('require arm64e code: ' + str(path))
            else:
                run('lipo', '-verify_arch', 'arm64e', path)
            detail = subprocess.run(['codesign', '--display', '--verbose=4', str(path)], check=True,
                                    capture_output=True, text=True).stderr
            match = re.search(r'^CDHash=([0-9a-f]{40})$', detail, re.M)
            if not match:
                raise SystemExit('no signed code identity: ' + str(path))
            hashes.append(match[1])
        addon, trust = work / 'lab-addon.bin', work / 'lab-trust.bundle'
        gpu = work / 'gpu-addon.bin'
        run(sys.executable, core / 'scripts/make-gpu-addon.py', '--publish', '--no-daemon',
            '--prefix', 'GPUBundles', '--prime-list', core / 'build/prime-list.txt', gpu,
            env=dict(os.environ, ADRENO_PLUGIN_DIR=str(args.plugin.resolve())))
        run(sys.executable, core / 'scripts/addon-add-dir.py', original_addon, addon,
            '--addon', gpu, 'test', files, 'test', ROOT / 'scripts/macos-lab', *bluetooth_dirs)
        run(sys.executable, core / 'scripts/trust-append-module.py', original_trust, trust, *sorted(set(hashes)))
        if args.refresh_payload:
            from unixnu.cli import parser as cli_parser
            from unixnu.config import Context
            from unixnu import bootimg, firmware, payload as fat_payload
            seed = work / 'scratch-data.img'
            run('mcopy', '-i', payload, '::/' + prefix.replace('kernel.macho.', '') + 'scratch-data.img', seed)
            chip = args.unique_chip_id
            if not chip:
                adt = work / 'original.adt'
                run('mcopy', '-i', payload, '::/' + prefix + 'adt', adt)
                data = adt.read_bytes()
                marker = b'unique-chip-id'.ljust(32, b'\0') + struct.pack('<I', 8)
                if data.count(marker) != 1:
                    parser.error('the input ADT requires one 64-bit unique-chip-id')
                chip = format(struct.unpack_from('<Q', data, data.index(marker)+len(marker))[0], 'x')
            options = cli_parser().parse_args(['build', 'payload', '-D', str(ROOT), '--os', 'macos-27',
                '--data-ramdisk', str(seed), '--owner-trust-cache', str(trust), '--gpu-addon', str(addon),
                '--uefi', str(args.uefi.resolve()), '--unique-chip-id', chip])
            ctx = Context(options)
            ctx.uefi = args.uefi.resolve()
            spec = ctx.board['payload']
            spec['size_mib'], spec['timeout'] = args.payload_mib, 1
            removed = {'exec-log', 'vc-text', 'storage-probe', 'data-reset', 'icon-cb'}
            if args.icon_dump_cb:
                removed.add('gpu-perf')
            spec['kernel_args'] = [item for item in spec['kernel_args'] if item.split('=', 1)[0] not in removed]
            options.kernel_arg = [f'autoreset={args.autoreset}', f'diag-export={args.autoreset-60}',
                'uefi-watchdog=1', 'diag=1', 'gpu-trace=1', 'log-gpu=1',
                'log-video=1', 'log-bluetooth=3', 'build-tag=s00000', 'ci-mps=0']
            options.kernel_arg += ['icon-cb='+args.icon_dump_cb] if args.icon_dump_cb else ['gpu-perf=1']
            fd = firmware.fd_path(ctx, ctx.uefi, 'DEBUG')
            # The template carries every firmware module built for this candidate.
            # Its ramdisk is empty; the account and OS remain private payload inputs.
            template = work / 'guarded-firmware.img'
            selected = ctx.board['bootimg'].pop('template', None)
            try:
                bootimg.build(ctx, ctx.uefi, fd, ctx.tree / ctx.board['bootimg']['dtb'], None, template)
            finally:
                if selected is not None:
                    ctx.board['bootimg']['template'] = selected
            import hashlib
            import lzma
            packed_template = args.output.with_suffix('.firmware.img.xz')
            packed_template.write_bytes(lzma.compress(template.read_bytes()))
            selected = dict(selected or {}, url=packed_template.resolve().as_uri(),
                            sha256=hashlib.sha256(packed_template.read_bytes()).hexdigest())
            ctx.board['bootimg']['template'] = selected
            previous = os.environ.get('UNIXNU_BOOT_TEMPLATE')
            os.environ['UNIXNU_BOOT_TEMPLATE'] = str(packed_template)
            try:
                fat_payload.build(ctx)
                bootimg.build(ctx, ctx.uefi, fd, None, fat_payload.paths(ctx)[1], args.output)
            finally:
                if previous is None:
                    os.environ.pop('UNIXNU_BOOT_TEMPLATE', None)
                else:
                    os.environ['UNIXNU_BOOT_TEMPLATE'] = previous
            return
        command = [sys.executable, ROOT / 'scripts/repack-sheng-boot.py', args.input, args.output,
                   '--payload-mib', args.payload_mib,
                   '--payload-file', str(addon) + '=' + prefix + 'gpuaddon',
                   '--payload-file', str(trust) + '=' + prefix + 'trustcache',
                   '--remove-arg', 'exec-log', '--remove-arg', 'vc-text', '--remove-arg', 'storage-probe',
                   '--remove-arg', 'icon-cb']
        for value in (f'autoreset={args.autoreset}', 'uefi-watchdog=1', 'diag=1', f'diag-export={args.autoreset-60}',
                      'gpu-trace=1', 'log-gpu=1', 'log-power=1', 'log-sys=1', 'log-display=1',
                      'log-video=1', 'log-bluetooth=3', 'build-tag=s00000'):
            command += ['--kernel-arg', value]
        if args.icon_dump_cb:
            command += ['--remove-arg', 'gpu-perf', '--kernel-arg', 'icon-cb='+args.icon_dump_cb]
        else:
            command += ['--kernel-arg', 'gpu-perf=1']
        if args.preserve_data:
            command += ['--remove-arg', 'data-reset']
        run(*command)
    print(f'GPU lab image: {args.output}; {len(set(hashes))} signed diagnostic images')


if __name__ == '__main__':
    main()
