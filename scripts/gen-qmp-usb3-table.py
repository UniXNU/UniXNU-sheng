#!/usr/bin/env python3
"""Write drivers/QcomDwc3/QcomQmpUsb3.h from the mainline QMP combo PHY tables for SM8550.

usage: gen-qmp-usb3-table.py LINUX_TREE OUTPUT. Register names resolve through the driver's own headers; offsets come from
qmp_combo_offsets_v3, the sm8550_usb3dpphy_cfg selection in phy-qcom-qmp-combo.c.
"""
import glob
import re
import sys
root, out = sys.argv[1], sys.argv[2]
q = root + '/drivers/phy/qualcomm/'
defs = {}
for path in glob.glob(q + 'phy-qcom-qmp*.h') + [q + 'phy-qcom-qmp-combo.c']:
    for m in re.finditer(r'^#define\s+(\w+)\s+(0x[0-9a-fA-F]+|\d+)\s*$', open(path).read(), re.M):
        defs.setdefault(m[1], int(m[2], 0))
src = open(q + 'phy-qcom-qmp-combo.c').read()


def table(name):
    body = re.search(r'static const struct qmp_phy_init_tbl ' + name + r'\[\] = \{(.*?)\n\};', src, re.S)[1]
    rows = []
    for m in re.finditer(r'QMP_PHY_INIT_CFG(_LANE)?\((\w+),\s*(0x[0-9a-fA-F]+|\d+)(?:,\s*(\w+))?\)', body):
        lane = int(m[4]) if m[1] else 0
        rows.append((defs[m[2]], int(m[3], 0), lane))
    return rows


OFF = dict(txa=0x1200, rxa=0x1400, txb=0x1600, rxb=0x1800, serdes=0x1000, misc=0x1a00, pcs=0x1c00, pcs_usb=0x1f00)
rows = []
rows += [(OFF['serdes'] + r, v) for r, v, _ in table('sm8550_usb3_serdes_tbl')]
for name, a, b in (('sm8550_usb3_tx_tbl', 'txa', 'txb'), ('sm8550_usb3_rx_tbl', 'rxa', 'rxb')):
    tbl = table(name)
    rows += [(OFF[a] + r, v) for r, v, lane in tbl if lane in (0, 1)]
    rows += [(OFF[b] + r, v) for r, v, lane in tbl if lane in (0, 2)]
rows += [(OFF['pcs'] + r, v) for r, v, _ in table('sm8550_usb3_pcs_tbl')]
rows += [(OFF['pcs_usb'] + r, v) for r, v, _ in table('sm8550_usb3_pcs_usb_tbl')]
pcs = {n: OFF['pcs'] + defs[v] for n, v in (('Reset', 'QPHY_V6_PCS_SW_RESET'), ('Start', 'QPHY_V6_PCS_START_CONTROL'),
                                             ('Status', 'QPHY_V6_PCS_PCS_STATUS1'), ('PowerDown', 'QPHY_V6_PCS_POWER_DOWN_CONTROL'))}
com = {n: defs[v] for n, v in (('ComMode', 'QPHY_V3_DP_COM_PHY_MODE_CTRL'), ('ComReset', 'QPHY_V3_DP_COM_SW_RESET'),
                               ('ComPower', 'QPHY_V3_DP_COM_POWER_DOWN_CTRL'), ('ComSwi', 'QPHY_V3_DP_COM_SWI_CTRL'),
                               ('ComTypec', 'QPHY_V3_DP_COM_TYPEC_CTRL'), ('ComResetOvrd', 'QPHY_V3_DP_COM_RESET_OVRD_CTRL'))}
text = '/* SPDX-License-Identifier: GPL-2.0-only\n * SM8550 QMP USB3/DP combo PHY, USB side. Generated by scripts/gen-qmp-usb3-table.py from Linux ' \
       'drivers/phy/qualcomm/phy-qcom-qmp-combo.c. */\n#ifndef QCOM_QMP_USB3_H\n#define QCOM_QMP_USB3_H\n#include <stdint.h>\n'
text += 'enum {' + ', '.join(f'kQmp{n} = {v:#x}' for n, v in list(pcs.items()) + list(com.items())) + '};\n'
text += 'static const struct {uint16_t offset; uint8_t value;} kQmpUsb3Init[] = {\n'
text += ''.join(f' {{{r:#x}, {v:#x}}},\n' for r, v in rows) + '};\n#endif\n'
open(out, 'w').write(text)
print(len(rows), 'writes', pcs, com)
